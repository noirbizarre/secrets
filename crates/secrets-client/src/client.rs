//! A thin, blocking client for `org.secrets.Manager`.
//!
//! Every method here is a direct proxy call — no local vault or session
//! state is cached or duplicated. `secretsd` is the sole authority on
//! locking and secret resolution; this type exists only to translate
//! `secrets_core::dbus::ManagerError` (this crate's [`crate::Error`])
//! into something a caller can match on, without ever touching `zbus`
//! itself.

use secrets_core::dbus::ManagerProxyBlocking;

use crate::{Error, Result};

/// Convert a raw `zbus` call result into this crate's [`Result`], routing
/// it through [`Error`] (`ManagerError`) first.
///
/// This matters: `ManagerError`'s `From<zbus::Error>` (generated by
/// `#[derive(DBusError)]`) is what recognises a named
/// `org.secrets.Error.*` reply and picks the matching variant — going
/// straight from `zbus::Error` to a caller-visible error via `?` would
/// skip that and collapse every daemon-side error into "unreachable".
fn map<T>(result: zbus::Result<T>) -> Result<T> {
    result.map_err(Error::from)
}

/// A connected client for `secretsd`'s native `org.secrets.Manager` API.
pub struct SecretsClient<'a> {
    proxy: ManagerProxyBlocking<'a>,
}

impl SecretsClient<'static> {
    /// Connect to `secretsd` on the session bus.
    ///
    /// # Errors
    ///
    /// Returns [`Error::Zbus`] if the session bus or the daemon cannot be
    /// reached — most commonly because `secretsd` is not running.
    pub fn connect() -> Result<Self> {
        let connection = map(zbus::blocking::Connection::session())?;
        let proxy = map(ManagerProxyBlocking::new(&connection))?;
        Ok(Self { proxy })
    }
}

impl SecretsClient<'_> {
    /// `"locked"` or `"unlocked"`.
    pub fn status(&self) -> Result<String> {
        map(self.proxy.status())
    }

    /// Unlock the store.
    pub fn unlock(&self, passphrase: &str) -> Result<()> {
        map(self.proxy.unlock(passphrase))
    }

    /// Lock the store.
    pub fn lock(&self) -> Result<()> {
        map(self.proxy.lock())
    }

    /// List every vault name.
    pub fn list_vaults(&self) -> Result<Vec<String>> {
        map(self.proxy.list_vaults())
    }

    /// List a vault's item paths.
    pub fn list_items(&self, vault: &str) -> Result<Vec<String>> {
        map(self.proxy.list_items(vault))
    }

    /// Validate a `secret://` reference without reading its value.
    pub fn resolve(&self, uri: &str) -> Result<String> {
        map(self.proxy.resolve(uri))
    }

    /// Fetch a field's value.
    pub fn get(&self, uri: &str) -> Result<String> {
        map(self.proxy.get(uri))
    }
}
