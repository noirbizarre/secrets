//! A thin, blocking client for `org.secrets.Manager`.
//!
//! Every method here is a direct proxy call — no local vault or session
//! state is cached or duplicated. `secretsd` is the sole authority on
//! locking and secret resolution; this type exists only to translate
//! `secrets_core::dbus::ManagerError` (this crate's [`crate::Error`])
//! into something a caller can match on, without ever touching `zbus`
//! itself.

use secrets_core::SecretValue;
use secrets_core::dbus::{FieldDisplay, ManagerProxyBlocking};

use crate::{Error, Result};

/// Convert a raw `zbus` call result into this crate's [`Result`], routing
/// it through [`Error`] (`ManagerError`) first.
///
/// This matters: `ManagerError`'s `From<zbus::Error>` (generated by
/// `#[derive(DBusError)]`) is what recognises a named
/// `org.secrets.Error.*` reply and picks the matching variant — going
/// straight from `zbus::Error` to a caller-visible error via `?` would
/// skip that and collapse every daemon-side error into "unreachable".
fn map<T>(result: zbus::Result<T>) -> Result<T> {
    result.map_err(Error::from)
}

/// A connected client for `secretsd`'s native `org.secrets.Manager` API.
pub struct SecretsClient<'a> {
    proxy: ManagerProxyBlocking<'a>,
}

impl SecretsClient<'static> {
    /// Connect to `secretsd` on the session bus.
    ///
    /// # Errors
    ///
    /// Returns [`Error::Zbus`] if the session bus or the daemon cannot be
    /// reached — most commonly because `secretsd` is not running.
    pub fn connect() -> Result<Self> {
        let connection = map(zbus::blocking::Connection::session())?;
        let proxy = map(ManagerProxyBlocking::new(&connection))?;
        Ok(Self { proxy })
    }
}

impl SecretsClient<'_> {
    /// `"locked"` or `"unlocked"` — a daemon-wide composite over every
    /// configured store (ADR-018); see [`SecretsClient::status_store`]
    /// for one store's own status.
    pub fn status(&self) -> Result<String> {
        map(self.proxy.status())
    }

    /// Unlock the store — a daemon-wide composite (ADR-018): a no-op
    /// with no real passphrase lock configured, unlocks directly with
    /// exactly one, and fails with `StoreSelectionRequired` with more
    /// than one; see [`SecretsClient::unlock_store`] to target a store
    /// explicitly.
    pub fn unlock(&self, passphrase: &str) -> Result<()> {
        map(self.proxy.unlock(passphrase))
    }

    /// Lock the store — a daemon-wide composite (ADR-018): locks every
    /// configured store; see [`SecretsClient::lock_store`] to target one.
    pub fn lock(&self) -> Result<()> {
        map(self.proxy.lock())
    }

    /// List every configured store's vault names, as `"<store>@<vault>"`
    /// strings (ADR-018) — always store-qualified, even with a single
    /// configured store.
    pub fn list_vaults(&self) -> Result<Vec<String>> {
        map(self.proxy.list_vaults())
    }

    /// List a vault's item paths. `vault` accepts the same optional
    /// `"<store>@"` prefix as a `secret://` URI's vault segment
    /// (ADR-018).
    pub fn list_items(&self, vault: &str) -> Result<Vec<String>> {
        map(self.proxy.list_items(vault))
    }

    /// List every configured store's id (ADR-018).
    pub fn list_stores(&self) -> Result<Vec<String>> {
        map(self.proxy.list_stores())
    }

    /// One store's own session state: `"locked"` or `"unlocked"`
    /// (ADR-018) — unlike [`SecretsClient::status`], never a composite.
    pub fn status_store(&self, store: &str) -> Result<String> {
        map(self.proxy.status_store(store))
    }

    /// Unlock exactly one store with its master passphrase (ADR-018).
    pub fn unlock_store(&self, store: &str, passphrase: &str) -> Result<()> {
        map(self.proxy.unlock_store(store, passphrase))
    }

    /// Lock exactly one store, dropping any decrypted material from
    /// memory (ADR-018).
    pub fn lock_store(&self, store: &str) -> Result<()> {
        map(self.proxy.lock_store(store))
    }

    /// Validate a `secret://` reference without reading its value.
    pub fn resolve(&self, uri: &str) -> Result<String> {
        map(self.proxy.resolve(uri))
    }

    /// Fetch a field's value.
    ///
    /// Wrapped in [`SecretValue`] the instant it arrives from the wire, so
    /// no caller of this crate can hold a bare, un-redacted `String` copy
    /// of a secret without going out of their way to `expose_secret()` it.
    pub fn get(&self, uri: &str) -> Result<SecretValue> {
        map(self.proxy.get(uri)).map(SecretValue::new)
    }

    /// Show every field of one item — name, kind, and either the real
    /// value or a fixed obfuscated placeholder, depending on the field's
    /// kind. See [`secrets_core::dbus::Manager::show_item`].
    ///
    /// `item_uri` is a `secret://<vault>/<item...>` reference with no
    /// field segment.
    pub fn show_item(&self, item_uri: &str) -> Result<Vec<FieldDisplay>> {
        map(self.proxy.show_item(item_uri))
    }
}
